-- schema.sql
-- Sales data schema for PostgreSQL

BEGIN;

CREATE TABLE IF NOT EXISTS customers (
    customer_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(100) NOT NULL,
    last_name        VARCHAR(100) NOT NULL,
    email            VARCHAR(255) UNIQUE,
    phone            VARCHAR(30),
    billing_address  TEXT,
    shipping_address TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    product_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(100) NOT NULL UNIQUE,
    product_name     VARCHAR(255) NOT NULL,
    description      TEXT,
    category         VARCHAR(150),
    unit_price       NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    currency_code    CHAR(3) NOT NULL DEFAULT 'USD',
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sales_orders (
    order_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number      VARCHAR(50) NOT NULL UNIQUE,
    customer_id       BIGINT NOT NULL REFERENCES customers(customer_id),
    order_date        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status            VARCHAR(20) NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'confirmed', 'processing',
                                        'shipped', 'delivered', 'cancelled', 'refunded')),
    currency_code     CHAR(3) NOT NULL DEFAULT 'USD',
    subtotal          NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount_amount   NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount        NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    shipping_amount   NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (shipping_amount >= 0),
    total_amount      NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    notes             TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (discount_amount <= subtotal)
);

CREATE TABLE IF NOT EXISTS order_items (
    order_item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES sales_orders(order_id) ON DELETE CASCADE,
    product_id       BIGINT NOT NULL REFERENCES products(product_id),
    quantity         INTEGER NOT NULL CHECK (quantity > 0),
    unit_price       NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    discount_amount  NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    line_total       NUMERIC(14, 2) GENERATED ALWAYS AS
                     ((quantity * unit_price) - discount_amount) STORED,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (discount_amount <= quantity * unit_price)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES sales_orders(order_id),
    payment_date     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount           NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    currency_code    CHAR(3) NOT NULL DEFAULT 'USD',
    payment_method   VARCHAR(30) NOT NULL
                     CHECK (payment_method IN ('card', 'cash', 'bank_transfer',
                                               'wallet', 'upi', 'other')),
    payment_status   VARCHAR(20) NOT NULL DEFAULT 'pending'
                     CHECK (payment_status IN ('pending', 'authorized', 'completed',
                                               'failed', 'refunded')),
    transaction_ref  VARCHAR(150) UNIQUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sales_orders_customer_id
    ON sales_orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_sales_orders_order_date
    ON sales_orders(order_date);
CREATE INDEX IF NOT EXISTS idx_sales_orders_status
    ON sales_orders(status);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id
    ON order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product_id
    ON order_items(product_id);
CREATE INDEX IF NOT EXISTS idx_payments_order_id
    ON payments(order_id);
CREATE INDEX IF NOT EXISTS idx_payments_payment_date
    ON payments(payment_date);

CREATE OR REPLACE VIEW sales_order_summary AS
SELECT
    o.order_id,
    o.order_number,
    o.order_date,
    o.status,
    o.customer_id,
    c.first_name,
    c.last_name,
    c.email,
    o.currency_code,
    o.subtotal,
    o.discount_amount,
    o.tax_amount,
    o.shipping_amount,
    o.total_amount,
    COALESCE(p.paid_amount, 0)::NUMERIC(14, 2) AS paid_amount
FROM sales_orders AS o
JOIN customers AS c ON c.customer_id = o.customer_id
LEFT JOIN (
    SELECT order_id, SUM(amount) AS paid_amount
    FROM payments
    WHERE payment_status = 'completed'
    GROUP BY order_id
) AS p ON p.order_id = o.order_id;

COMMIT;
